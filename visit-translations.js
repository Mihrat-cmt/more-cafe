// APPLY VISIT PAGE TRANSLATIONS
// ==========================================

// Update aria-label attributes when the language changes.
function applyVisitTranslations(language) {
    const discoverLink = document.querySelector(
        '.visit-round-link[data-i18n-aria-label]'
    );

    if (discoverLink) {
        const key = discoverLink.getAttribute('data-i18n-aria-label');
        const translation = translations[language]?.[key];

        if (translation) {
            discoverLink.setAttribute('aria-label', translation);
        }
    }
}

// Apply the saved language after the translations have been added.
const visitSavedLanguage = localStorage.getItem('moreLanguage') || 'en';

if (typeof setLanguage === 'function') {
    setLanguage(visitSavedLanguage);
    applyVisitTranslations(visitSavedLanguage);
}

// Keep the accessibility label updated when the language changes.
document.querySelectorAll('[data-language]').forEach(button => {
    button.addEventListener('click', () => {
        const language = button.dataset.language;

        setTimeout(() => {
            applyVisitTranslations(language);
        }, 0);
    });
});